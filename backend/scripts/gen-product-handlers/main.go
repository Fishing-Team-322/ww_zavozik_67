// Command gen-product-handlers generates strict adapters from the shared OpenAPI.
package main

import (
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/getkin/kin-openapi/openapi3"
)

func main() {
	root := flag.String("root", ".", "backend module directory")
	flag.Parse()
	dir := filepath.Join(*root, "internal/httpapi")
	implemented := map[string]bool{}
	files, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		panic(err)
	}
	for _, file := range files {
		if strings.HasSuffix(file, ".gen.go") || strings.HasSuffix(file, "_test.go") {
			continue
		}
		f, e := parser.ParseFile(token.NewFileSet(), file, nil, 0)
		if e != nil {
			panic(e)
		}
		for _, decl := range f.Decls {
			fn, ok := decl.(*ast.FuncDecl)
			if !ok || fn.Recv == nil || len(fn.Recv.List) != 1 {
				continue
			}
			recv, ok := fn.Recv.List[0].Type.(*ast.StarExpr)
			if !ok {
				continue
			}
			id, ok := recv.X.(*ast.Ident)
			if ok && id.Name == "Server" {
				implemented[fn.Name.Name] = true
			}
		}
	}
	spec, err := openapi3.NewLoader().LoadFromFile(filepath.Join(*root, "../api/openapi.yaml"))
	if err != nil {
		panic(err)
	}
	operations := []string{}
	for _, item := range spec.Paths.Map() {
		for _, op := range item.Operations() {
			name := strings.ToUpper(op.OperationID[:1]) + op.OperationID[1:]
			if !implemented[name] {
				operations = append(operations, op.OperationID)
			}
		}
	}
	sort.Strings(operations)
	var b strings.Builder
	b.WriteString("// Code generated by scripts/gen-product-handlers; DO NOT EDIT.\npackage httpapi\nimport(\"context\";\"net/http\")\n")
	for _, op := range operations {
		name := strings.ToUpper(op[:1]) + op[1:]
		upload := "nil"
		if op == "uploadStatement" {
			upload = "r.Body"
		}
		fmt.Fprintf(&b, "func(s *Server) %s(ctx context.Context,r %sRequestObject)(%sResponseObject,error){return s.productReply(ctx,%q,%s)}\nfunc(a reply) Visit%sResponse(w http.ResponseWriter)error{return a.write(w)}\n", name, name, name, op, upload, name)
	}
	source, err := format.Source([]byte(b.String()))
	if err != nil {
		panic(err)
	}
	if err = os.WriteFile(filepath.Join(dir, "product.gen.go"), source, 0644); err != nil {
		panic(err)
	}
}
