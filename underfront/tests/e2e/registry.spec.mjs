import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { mkdirSync } from 'node:fs';
import path from 'node:path';

test('official registry PDF previews, links explicitly, survives reload and never creates bank facts', async ({ page, request }) => {
  test.skip(!process.env.LIVE_FNS_PDF, 'Opt in with LIVE_FNS_PDF; no official document is committed.');
  const api = process.env.E2E_API_URL || 'http://localhost:8080';
  const email = `registry-${randomUUID()}@example.invalid`;
  const password = 'E2e!A1b2C3d4';
  const response = await request.post(`${api}/v1/auth/register`, { data: { email, password, consent_pd: true } });
  expect(response.status()).toBe(201);
  const headers = { Authorization: `Bearer ${(await response.json()).access_token}` };
  await page.goto('/login');
  await page.getByRole('textbox', { name: 'Электронная почта' }).fill(email);
  await page.getByRole('textbox', { name: 'Пароль', exact: true }).fill(password);
  await page.getByRole('button', { name: 'Войти', exact: true }).click();
  await expect(page).toHaveURL(/\/companies\/new$/);
  await page.getByRole('textbox', { name: 'Название компании' }).fill('V2 registry test workspace');
  await page.getByRole('textbox', { name: 'Вид деятельности' }).fill('Tests');
  await page.getByRole('button', { name: 'Создать компанию', exact: true }).click();
  await expect(page).toHaveURL(/\/sources$/);
  const profile = await request.get(`${api}/v1/me`, { headers });
  const cid = (await profile.json()).companies[0].id;
  const registry = page.locator('#registry-documents');
  const upload = () => registry.locator('input[type="file"]').setInputFiles(process.env.LIVE_FNS_PDF);
  await upload();
  await expect(registry.getByRole('heading', { name: 'Предпросмотр реквизитов' })).toBeVisible();
  await expect(registry).toContainText('6164138513');
  await expect(registry).toContainText('1226100018561');
  await expect(registry).toContainText('2026-10-24');
  await expect(registry).toContainText('NOT_VERIFIED');
  const before = await request.get(`${api}/v1/companies/${cid}/registry`, { headers });
  expect(await before.json()).toEqual([]);
  await registry.getByRole('button', { name: 'Подтвердить и сохранить сведения ФНС' }).click();
  await expect(registry.getByRole('status')).toContainText('Сведения ФНС сохранены');
  await upload();
  await expect(registry.getByRole('heading', { name: 'Предпросмотр реквизитов' })).toBeVisible();
  await registry.getByRole('button', { name: 'Подтвердить и сохранить сведения ФНС' }).click();
  await expect(registry.getByRole('heading', { name: 'Предпросмотр реквизитов' })).not.toBeVisible();
  await page.reload();
  await expect(registry.getByRole('article')).toHaveCount(1);
  const list = await request.get(`${api}/v1/companies/${cid}/registry`, { headers });
  const records = await list.json();
  expect(records).toHaveLength(1);
  expect(records[0].ownership_verified).toBe(false);
  expect(records[0].bank_account_verified).toBe(false);
  const operations = await request.get(`${api}/v1/companies/${cid}/operations`, { headers });
  expect((await operations.json()).items).toHaveLength(0);
  const dashboard = await request.get(`${api}/v1/companies/${cid}/dashboard`, { headers });
  expect((await dashboard.json()).balance_now).toBe(null);
  const shots = process.env.E2E_SCREENSHOTS_DIR || path.resolve('test-results/screenshots');
  mkdirSync(shots, { recursive: true });
  await registry.screenshot({ path: path.join(shots, 'fns-registry-saved-redacted.png'), mask: [registry.getByRole('article')] });
  await page.goto('/counterparties');
  const detail = await request.get(`${api}/v1/companies/${cid}/counterparties`, { headers });
  const parties = await detail.json();
  expect(parties).toHaveLength(1);
  await page.locator(`a[href="/counterparties/${parties[0].id}"]`).click();
  await expect(page.locator('main')).toContainText('NOT_VERIFIED');
  await expect(page.locator('main').getByRole('alert')).toHaveCount(0);
});
