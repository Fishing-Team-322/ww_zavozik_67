import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { mkdirSync, readFileSync } from 'node:fs';
import path from 'node:path';

test('invoice partial payment, recurring schedule, settings, export and theme persist through the UI', async ({ page, request }) => {
  const api = process.env.E2E_API_URL || 'http://localhost:8080';
  const email = `finance-${randomUUID()}@example.invalid`; const password = 'E2e!A1b2C3d4';
  const registered = await request.post(`${api}/v1/auth/register`, { data: { email, password, consent_pd: true } });
  expect(registered.status()).toBe(201);
  const headers = { Authorization: `Bearer ${(await registered.json()).access_token}` };
  const company = await request.post(`${api}/v1/companies`, { headers, data: { name: 'Synthetic finance CRUD', legal_form: 'ООО', industry: 'Tests' } });
  expect(company.status()).toBe(201); const cid = (await company.json()).id;
  const errors=[]; page.on('pageerror', error=>errors.push(error.message));
  await page.goto('/login'); await page.getByLabel('Электронная почта', { exact: true }).fill(email);
  await page.getByLabel('Пароль', { exact: true }).fill(password); await page.getByRole('button', { name: 'Войти', exact: true }).click();
  await expect(page).toHaveURL(/\/overview$/);
  await page.goto('/documents');
  await page.getByRole('button', { name: 'Добавить счёт', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Номер', { exact: true }).fill('SYNTHETIC-350');
  await dialog.getByLabel('Контрагент', { exact: true }).fill('Synthetic customer');
  await dialog.getByLabel('Сумма, ₽', { exact: true }).fill('350000');
  await dialog.getByLabel('Оплачено, ₽', { exact: true }).fill('100000');
  await dialog.getByRole('button', { name: 'Статус', exact: true }).click();
  await page.getByRole('option', { name: 'Частично оплачен', exact: true }).click();
  await dialog.getByRole('button', { name: 'Сохранить', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  const row = page.getByRole('row').filter({ hasText: 'SYNTHETIC-350' }); await expect(row).toContainText('Частично оплачен');
  const invoices = await request.get(`${api}/v1/companies/${cid}/invoices`, { headers }); const invoice = (await invoices.json())[0];
  expect(invoice.amount).toBe(350000); expect(invoice.paid_amount).toBe(100000);
  const events = await request.get(`${api}/v1/companies/${cid}/events`, { headers });
  expect((await events.json()).some(event => event.amount === 250000)).toBe(true);
  const facts = await request.get(`${api}/v1/companies/${cid}/operations`, { headers }); expect((await facts.json()).items).toHaveLength(0);
  await row.getByRole('button', { name: 'Изменить', exact: true }).click();
  await dialog.getByLabel('Оплачено, ₽', { exact: true }).fill('350000');
  await dialog.getByRole('button', { name: 'Статус', exact: true }).click(); await page.getByRole('option', { name: 'Оплачен', exact: true }).click();
  await dialog.getByRole('button', { name: 'Сохранить', exact: true }).click(); await expect(dialog).toHaveCount(0);
  await page.reload(); await expect(row).toContainText('Оплачен');
  await page.getByRole('tab',{name:'Договоры',exact:true}).click();
  await page.getByRole('button',{name:'Добавить договор',exact:true}).click();
  await dialog.getByLabel('Номер',{exact:true}).fill('SYNTHETIC-CONTRACT');
  await dialog.getByLabel('Сумма, ₽',{exact:true}).first().fill('100000');
  await dialog.getByLabel('Сумма, ₽',{exact:true}).last().fill('100000');
  await dialog.getByRole('button',{name:'Сохранить',exact:true}).click();
  await expect(dialog).toHaveCount(0);await expect(page.getByRole('row').filter({hasText:'SYNTHETIC-CONTRACT'})).toBeVisible();
  const contracts=await request.get(`${api}/v1/companies/${cid}/contracts`,{headers});expect((await contracts.json())[0].total).toBe(100000);
  await page.goto('/recurring'); await page.getByRole('button', { name: 'Добавить платёж', exact: true }).click();
  await dialog.getByLabel('Название', { exact: true }).fill('Synthetic rent');
  await dialog.getByLabel('Сумма, ₽', { exact: true }).fill('12345.67');
  await dialog.getByRole('button', { name: 'Сохранить', exact: true }).click(); await expect(dialog).toHaveCount(0);
  const recurring = page.getByRole('row').filter({ hasText: 'Synthetic rent' }); await expect(recurring).toContainText('Подтверждён');
  await recurring.getByRole('button', { name: 'Отключить', exact: true }).click(); await expect(recurring).toContainText('Отключён');
  await page.reload(); await expect(recurring).toContainText('Отключён');
  await page.goto('/settings'); await page.getByLabel('Защитный резерв, ₽', { exact: true }).fill('50000');
  await page.getByRole('button', { name: 'Сохранить настройки', exact: true }).click();
  await expect.poll(async () => (await (await request.get(`${api}/v1/companies/${cid}`, { headers })).json()).reserve).toBe(50000);
  await page.reload(); await expect(page.getByLabel('Защитный резерв, ₽', { exact: true })).toHaveValue('50000');
  await page.getByRole('button', { name: 'Экспортировать', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Скачать архив', exact: true })).toBeVisible({ timeout: 60_000 });
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button', { name: 'Скачать архив', exact: true }).click();
  const downloaded=await downloadPromise;
  expect(readFileSync(await downloaded.path()).subarray(0,2).toString()).toBe('PK');
  await page.getByRole('button', { name: 'Тёмная тема', exact: true }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark'); await page.reload();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  const shots=process.env.E2E_SCREENSHOTS_DIR || path.resolve('../docs/e2e-v2-screenshots'); mkdirSync(shots,{recursive:true});
  await page.screenshot({path:path.join(shots,'settings-dark-synthetic.png')});
  await page.getByRole('button', { name: 'Светлая тема', exact: true }).click();
  expect(errors).toEqual([]);
});
