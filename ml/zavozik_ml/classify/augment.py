TYPO_SWAP = {"о": "а", "а": "о", "е": "и", "и": "е", "я": "а", "ю": "у", "ы": "и", "т": "д", "с": "з", "ч": "щ"}
LAT = str.maketrans("аеорсухАЕОРСХКМТВН", "aeopcyxAEOPCXKMTBH")


def typo(text: str, rng: random.Random, p: float = 0.15) -> str:
    words = text.split(" ")
    for i, w in enumerate(words):
        if len(w) < 4 or rng.random() > p:
            continue
        j = rng.randrange(1, len(w) - 1)
        op = rng.randrange(4)
        if op == 0:
            w = w[:j] + w[j + 1:]
        elif op == 1:
            w = w[:j] + w[j] + w[j:]
        elif op == 2:
            w = w[:j - 1] + w[j] + w[j - 1] + w[j + 1:]
        else:
            w = w[:j] + TYPO_SWAP.get(w[j], w[j]) + w[j + 1:]
        words[i] = w
    return " ".join(words)


def abbreviate(text: str, rng: random.Random) -> str:
    for pat, repl in ABBR:
        if rng.random() < 0.6:
            text = re.sub(pat, lambda _: rng.choice(repl), text, flags=re.I)
    return text


def drop_parts(text: str, rng: random.Random) -> str:
    r = rng.random()
    if r < 0.35:
        text = re.split(r"\.\s", text)[0]
    elif r < 0.6:
        text = re.sub(r"(по|согласно)\s+(счету|договору|УПД|накладной|акту)[^.,]*", "", text, flags=re.I)
    elif r < 0.8:
        words = text.split()
        if len(words) > 3:
            k = rng.randint(2, len(words) - 1)
            text = " ".join(words[:k])
    else:
        text = re.sub(r"\d[\d\s.,/-]*", "", text)
    return " ".join(text.split())


def add_channel(text: str, rng: random.Random) -> str:
    ch = rng.choice(CHANNELS).replace("{n}", _n(rng))
    parts = re.split(r"\.\s", text, maxsplit=1)
    if rng.random() < 0.5 or len(parts) == 1:
        return f"{text} {ch}".strip()
    return f"{parts[0]} {ch}. {parts[1]}"


def case(text: str, rng: random.Random) -> str:
    r = rng.random()
    if r < 0.4:
        return text.upper()
    if r < 0.8:
        return text.lower()
    return text.translate(LAT) if rng.random() < 0.5 else text


# Категории, где канал платежа и есть смысл (розничная выручка): каналы не добавляем.
CHANNEL_IS_CATEGORY = {"revenue_acquiring", "revenue_sbp", "revenue_cash", "revenue_marketplace"}


def perturb(row: dict, rng: random.Random) -> dict:
    """Шумная копия реальной операции: тот же смысл — та же метка."""
    r = dict(row)
    p = r["purpose"]
    if rng.random() < 0.5:
        p = drop_parts(p, rng)
    if rng.random() < 0.35 and r["label"] not in CHANNEL_IS_CATEGORY:
        p = add_channel(p, rng)
    if rng.random() < 0.3:
        p = abbreviate(p, rng)
    if rng.random() < 0.35:
        p = typo(p, rng)
    if rng.random() < 0.2:
        p = case(p, rng)
    r["purpose"] = p
    if rng.random() < 0.25:  # обезличенный контрагент: смысл должен идти из назначения
        if r["inn_type"] == "person":
            r["name"] = f"{rng.choice(SURNAMES)} {rng.choice(['Иван', 'Анна', 'Сергей', 'Ольга'])}"
        elif r["name"] and not re.search(r"банк|казначейств|учредител|участник|сотрудник", r["name"], re.I):
            r["name"] = _generic_org(rng)
    return r


def _fill(tpl: str, rng: random.Random) -> str:
    goods = rng.choice(GOODS)
    svc = rng.choice(SERVICES)
    s = (tpl.replace("{goods}", goods).replace("{goods_gen}", rng.choice(GOODS_GEN))
         .replace("{services}", svc).replace("{services_cap}", svc[:1].upper() + svc[1:])
         .replace("{media}", rng.choice(MEDIA)).replace("{bank}", rng.choice(["АО «Банк-2»", "другом банке", "ПАО «Сбербанк»", "АО «Альфа-Банк»", "банке ВТБ"]))
         .replace("{fio}", _fio(rng)).replace("{year}", rng.choice(["2025", "2026", "2027"]))
         .replace("{junk}", "".join(rng.choice("абвгдежзиклмнопрстуфхцчшщэюя") for _ in range(rng.randint(3, 12))))
         .replace("{digits}", str(rng.randint(1, 10**8))))
    while "{" in s:
        s = (s.replace("{doc}", _doc(rng), 1).replace("{period}", _period(rng), 1).replace("{n}", _n(rng), 1)
             .replace("{date}", _date(rng), 1).replace("{region}", rng.choice(REGIONS), 1))
    return " ".join(s.split())


def _name_for(cat_key: str, spec: dict, rng: random.Random) -> tuple[str, str]:
    """Название и тип контрагента для синтетики (без «говорящих» основ)."""
    cat = spec.get("cat", cat_key)
    if cat in ("salary",):
        return rng.choice([(f"Сотрудник {_fio(rng)}", "person"), (rng.choice(BANKS), "org"),
                           (f"{rng.choice(SURNAMES)} {rng.choice(['Иван', 'Анна', 'Ольга'])} {rng.choice(['Петрович', 'Сергеевна', 'Олегович'])}", "person")])
    if cat in ("bank_fee", "loan_payment", "revenue_acquiring", "revenue_sbp", "revenue_cash") or cat_key == "own_transfer_in":
        return (rng.choice(BANKS), rng.choice(["org", "org", "none"]))
    if cat == "own_transfer":
        return rng.choice([(rng.choice(BANKS), "org"), (_generic_org(rng), "org"),
                           (f"ИП {rng.choice(SURNAMES)} {rng.choice('АБВГД')}.{rng.choice('АБВГД')}.", "person")])
    if cat == "other":
        return rng.choice([(_generic_org(rng), "org"), (f"{rng.choice(SURNAMES)} {rng.choice(['Иван', 'Анна'])}", "person"),
                           (rng.choice(BANKS), "org"), ("", "none"), ("Физическое лицо", "person")])
    if cat in ("revenue_b2b", "refund") and rng.random() < 0.3:
        return (f"{rng.choice(SURNAMES)} {rng.choice(['Иван', 'Анна', 'Ольга'])}", "person")
    return (_generic_org(rng), "org")


def _telling_name(spec: dict, rng: random.Random) -> tuple[str, str] | None:
    """«Говорящее» название контрагента из словаря категории (или None)."""
    names = spec.get("names")
    if names:
        stem = rng.choice(names)
        if "{" in stem or "(" in stem or "России" in stem:
            return (_fill(stem, rng), "org")
        if stem.startswith(("Учредитель", "Участник")):
            return (stem if "(" in stem else f"{stem} {_fio(rng)}", "person")
        return (_org(rng, stem), "org" if rng.random() < 0.8 else "person")
    return None


def synth(rng: random.Random, n_per_cat: int) -> list[dict]:
    out = []
    for key, spec in SYNTH.items():
        cat = spec.get("cat", key)
        k = n_per_cat if key == spec.get("cat", key) else n_per_cat // 3
        for _ in range(k):
            purpose = _fill(rng.choice(spec["heads"]), rng)
            v = _vat(rng)
            if v and cat != "other" and rng.random() < 0.5:
                purpose = f"{purpose}. {v}"
            if cat not in CHANNEL_IS_CATEGORY and cat != "other" and rng.random() < 0.25:
                purpose = add_channel(purpose, rng)
            if rng.random() < 0.15:
                purpose = abbreviate(purpose, rng)
            if rng.random() < 0.2:
                purpose = typo(purpose, rng)
            if rng.random() < 0.1:
                purpose = case(purpose, rng)
            telling = _telling_name(spec, rng) if rng.random() < 0.6 else None
            name, itype = telling or _name_for(key, spec, rng)
            d = spec["dir"] or rng.choice(["in", "out"])
            # Пустое назначение с «говорящим» контрагентом.
            if telling and rng.random() < 0.2:
                purpose = ""
            out.append(dict(direction=d, purpose=purpose, name=name, inn_type=itype,
                            amount=10 ** rng.uniform(2, 6.5), label=cat))
    # Пустое (или пустое после нормализации) назначение и ничего не говорящий
    # контрагент — смысл не определить: other.
    for _ in range(n_per_cat // 2):
        name, itype = _name_for("other", SYNTH["other"], rng)
        out.append(dict(direction=rng.choice(["in", "out"]), purpose=rng.choice(["", "", "-", ".", "б/н", "0"]),
                        name=name, inn_type=itype, amount=10 ** rng.uniform(2, 6.5), label="other"))
    return out
