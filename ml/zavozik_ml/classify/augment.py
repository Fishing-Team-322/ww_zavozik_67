def _generic_org(rng: random.Random) -> str:
    form = rng.choice(["ООО", "ООО", "АО", "ПАО", "ИП"])
    if form == "ИП":
        return f"ИП {rng.choice(SURNAMES)} {rng.choice('АБВГДЕИКЛМН')}.{rng.choice('АБВГДЕИКЛМН')}."
    return f"{form} «{rng.choice(GENERIC_ORG)}{rng.choice(['', '', '-' + str(rng.randint(1, 999)), ' Плюс', ' Групп'])}»"


def _org(rng: random.Random, stem: str) -> str:
    form = rng.choice(["ООО", "ООО", "АО", "ИП"])
    suffix = rng.choice(["", "", f"-{rng.randint(1, 999)}", " Юг", " Плюс", " Центр", f" № {rng.randint(1, 9)}"])
    return f"{form} {stem}{suffix}" if form == "ИП" else f"{form} «{stem}{suffix}»"


